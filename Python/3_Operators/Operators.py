# Comparison Operators

print("3 > 2:", 3 > 2)
print("3 >= 2:", 3 >= 2)
print("3 < 2:", 3 < 2)
print("2 < 3:", 2 < 3)
print("2 <= 3:", 2 <= 3)
print("3 == 2:", 3 == 2)
print("3 != 2:", 3 != 2)

